export function essayPhrases(day: number) {
  const index = Math.min(Math.max(day, 1), 10) - 1;
  return groups.map((group) => ({
    title: group.title,
    items: group.items.map((item) => ({
      phrase: item.phrase,
      meaning: item.meaning,
      example: item.examples[index] ?? item.examples[0],
    })),
  }));
}
